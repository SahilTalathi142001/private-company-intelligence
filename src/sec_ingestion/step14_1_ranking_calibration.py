# ============================================================================
# COMPANY DISCOVERY
# ============================================================================

def discover_ciks(
    features_path: Path,
) -> List[str]:

    ciks = []

    for path in sorted(
        features_path.glob(
            "cik=*/financial_features.parquet"
        )
    ):

        cik = path.parent.name.replace(
            "cik=",
            "",
        )

        if cik:
            ciks.append(
                cik
            )

    return sorted(
        set(ciks)
    )


