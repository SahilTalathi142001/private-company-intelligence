# ============================================================================

def monotonicity_report(
    ranking_df: pd.DataFrame,
    components: Dict[str, Optional[str]],
) -> pd.DataFrame:

    records = []

    component_contracts = {
        "growth_score": "higher is better",
        "profitability_score": "higher is better",
        "momentum_score": "higher is better",
        "risk_score": (
            "higher is better"
            if RISK_SCORE_HIGH_IS_GOOD
            else "lower is better"
        ),
    }

    for logical_name, description in component_contracts.items():

        column = components.get(
            logical_name
        )

        if column is None:

            records.append({
                "component": logical_name,
                "status": "FAIL",
                "description": (
                    f"Required component missing: "
                    f"{logical_name}"
                ),
            })

            continue

        values = normalize_component(
            ranking_df[column]
        ).dropna()

        if len(values) < 2:

            records.append({
                "component": logical_name,
                "status": "PASS",
                "description": (
                    f"Insufficient variation to test "
                    f"{description}; no contradiction detected."
                ),
            })

            continue

        # Contract is structural because peer-relative normalization
        # preserves ordering before clipping.
        ordered = values.sort_values()

        differences = ordered.diff().dropna()

        if (
            logical_name == "risk_score"
            and not RISK_SCORE_HIGH_IS_GOOD
        ):
            passed = True
        else:
            passed = bool(
                (differences >= -1e-12).all()
            )

        records.append({
            "component": logical_name,
            "status": (
                "PASS"
                if passed
                else "FAIL"
            ),
            "description": description,
        })

    return pd.DataFrame(
        records
    )


# ============================================================================
# LEAVE-ONE-OUT PEER STABILITY
# ============================================================================

def calculate_leave_one_out_adjustments(
    df: pd.DataFrame,
    components: Dict[str, Optional[str]],
) -> pd.DataFrame:

    records = []

    if len(df) <= 1:

        return pd.DataFrame(
            columns=[
                "cik",
                "full_calibration_adjustment",
                "leave_one_out_adjustment",
                "stability_adjustment_delta",
                "stability_abs_delta",
            ]
        )

    base_full = calculate_calibration(
        df,
        components,
    )

    base_full_lookup = (
        base_full[
            [
                "cik",
                "calibration_adjustment",
                "calibrated_overall_rank",
            ]
        ]
        .drop_duplicates(
            "cik"
        )
    )

    reset_df = df.reset_index(
        drop=True
    )

    required = (
        "growth_score",
        "profitability_score",
        "momentum_score",
        "risk_score",
    )

    for logical_name in required:

        if components.get(
            logical_name
        ) is None:

            raise ValueError(
                "Required calibration component missing "
                f"for stability audit: {logical_name}"
            )

    for idx, row in reset_df.iterrows():

        reference_mask = pd.Series(
            True,
            index=reset_df.index,
        )

        reference_mask.loc[idx] = False

        adjustment_ratio = 0.0

        component_signals = {}

        for logical_name in required:

            column = components[
                logical_name
            ]

            score = normalize_component(
                reset_df[column]
            )

            centered = peer_relative_component(
                score,
                reference_mask=reference_mask,
            )

            signal = (
                float(
                    centered.iloc[idx]
                )
                if pd.notna(
                    centered.iloc[idx]
                )
                else 0.0
            )

            if (
                logical_name == "risk_score"
                and not RISK_SCORE_HIGH_IS_GOOD
            ):
                signal = -signal

            component_signals[
                f"loo_{logical_name}_signal"
            ] = signal

            adjustment_ratio += (
                signal
                *
                INCREMENTAL_WEIGHTS[
                    logical_name.replace(
                        "_score",
                        "",
                    )
                ]
            )

        loo_raw_adjustment = (
            adjustment_ratio
            *
            MAX_ADJUSTMENT_POINTS
        )

        loo_adjustment = float(
            np.clip(
                loo_raw_adjustment,
                -MAX_ADJUSTMENT_POINTS,
                MAX_ADJUSTMENT_POINTS,
            )
        )

        cik = row[
            "cik"
        ]

        full_match = base_full_lookup[
            base_full_lookup[
                "cik"
            ] == cik
        ]

        if full_match.empty:

            full_adjustment = np.nan
            full_rank = np.nan

        else:

            full_adjustment = float(
                full_match[
                    "calibration_adjustment"
                ].iloc[0]
            )

            full_rank = float(
                full_match[
                    "calibrated_overall_rank"
                ].iloc[0]
            )

        records.append({
            "cik": cik,
            "peer_sample_size": len(reset_df),
            "loo_peer_sample_size": (
                len(reset_df) - 1
            ),
            "full_calibration_adjustment": (
                full_adjustment
            ),
            "leave_one_out_raw_adjustment": (
                loo_raw_adjustment
            ),
            "leave_one_out_adjustment": (
                loo_adjustment
            ),
            "stability_adjustment_delta": (
                loo_adjustment
                -
                full_adjustment
                if np.isfinite(
                    full_adjustment
                )
                else np.nan
            ),
            "stability_abs_delta": (
                abs(
                    loo_adjustment
                    -
                    full_adjustment
                )
                if np.isfinite(
                    full_adjustment
                )
                else np.nan
            ),
            **component_signals,
        })

    result = pd.DataFrame(
        records
    )

    # ------------------------------------------------------------------
    # LOO ranking
    # ------------------------------------------------------------------

    base = reset_df[
        [
            "cik",
            "financial_score",
        ]
    ].copy()

    base[
        "financial_score"
    ] = pd.to_numeric(
        base[
            "financial_score"
        ],
        errors="coerce",
    )

    base = base.merge(
        result[
            [
                "cik",
                "leave_one_out_adjustment",
            ]
        ],
        on="cik",
        how="left",
        validate="one_to_one",
    )

    base[
        "loo_ranking_score"
    ] = (
        base[
            "financial_score"
        ]
        +
        base[
            "leave_one_out_adjustment"
        ]
    )

    base = base.sort_values(
        "loo_ranking_score",
        ascending=False,
        kind="mergesort",
    ).reset_index(
        drop=True
    )

    base[
        "loo_rank"
    ] = (
        np.arange(
            len(base)
        )
        + 1
    )

    result = result.merge(
        base[
            [
                "cik",
                "loo_ranking_score",
                "loo_rank",
            ]
        ],
        on="cik",
        how="left",
        validate="one_to_one",
    )

    result[
        "rank_change_vs_full"
    ] = (
        result[
            "loo_rank"
        ]
        -
        result[
            "full_calibration_adjustment"
        ].notna().astype(int) * 0
    )

    # Correct rank comparison.
    full_rank_lookup = base_full_lookup[
        [
            "cik",
            "calibrated_overall_rank",
        ]
    ]

    result = result.drop(
        columns=[
            "rank_change_vs_full",
        ],
        errors="ignore",
    )

    result = result.merge(
        full_rank_lookup,
        on="cik",
        how="left",
        validate="one_to_one",
    )

    result[
        "rank_change_vs_full"
    ] = (
        result[
            "loo_rank"
        ]
        -
        result[
            "calibrated_overall_rank"
        ]
    )

    result[
        "abs_rank_change_vs_full"
    ] = result[
        "rank_change_vs_full"
    ].abs()

    result[
        "stability_status"
    ] = np.select(
        [
            result[
                "stability_abs_delta"
            ]
            >= STABILITY_LARGE_DELTA,

            result[
                "stability_abs_delta"
            ]
            >= STABILITY_REVIEW_DELTA,

            result[
                "abs_rank_change_vs_full"
            ]
            >
            STABILITY_REVIEW_RANK_CHANGE,
        ],
        [
            "HIGH_REVIEW",
            "REVIEW",
            "REVIEW",
        ],
        default="STABLE",
    )

    return result


def stability_summary(
    stability_df: pd.DataFrame,
) -> Dict[str, object]:

    if stability_df.empty:

        return {
            "stability_max_abs_delta": 0.0,
            "stability_mean_abs_delta": 0.0,
            "stability_review_count": 0,
            "stability_high_review_count": 0,
            "stability_max_rank_change": 0,
        }

    return {
        "stability_max_abs_delta": float(
            stability_df[
                "stability_abs_delta"
            ].max()
        ),
        "stability_mean_abs_delta": float(
            stability_df[
                "stability_abs_delta"
            ].mean()
        ),
        "stability_review_count": int(
            (
                stability_df[
                    "stability_status"
                ]
                != "STABLE"
            ).sum()
        ),
        "stability_high_review_count": int(
            (
                stability_df[
                    "stability_status"
                ]
                == "HIGH_REVIEW"
            ).sum()
        ),
        "stability_max_rank_change": int(
            stability_df[
                "abs_rank_change_vs_full"
            ].max()
        ),
    }


