def component_quality_report(
    ranking_df: pd.DataFrame,
    components: Dict[str, Optional[str]],
) -> pd.DataFrame:

    records = []

    for logical_name, column in components.items():

        if column is None:

            records.append({
                "component": logical_name,
                "source_column": None,
                "present": False,
                "row_count": len(ranking_df),
                "non_null_rows": 0,
                "unique_values": 0,
                "mean": np.nan,
                "std": np.nan,
                "min": np.nan,
                "max": np.nan,
                "constant": False,
                "usable_for_calibration": False,
                "included_in_calibration": (
                    logical_name
                    in INCREMENTAL_WEIGHTS
                ),
                "exclusion_reason": (
                    "MISSING_COMPONENT"
                ),
            })

            continue

        series = numeric_series(
            ranking_df,
            column,
        )

        valid = series[
            np.isfinite(series)
        ]

        unique_count = int(
            valid.nunique(
                dropna=True
            )
        )

        std = (
            float(
                valid.std(
                    ddof=0
                )
            )
            if len(valid)
            else np.nan
        )

        constant = (
            len(valid) > 0
            and np.isfinite(std)
            and std <= VARIANCE_EPSILON
        )

        included = (
            logical_name
            in INCREMENTAL_WEIGHTS
            and not constant
        )

        if logical_name == "financial_strength_score":

            included = False
            exclusion_reason = (
                "BASE_SCORE_DUPLICATE"
            )

        elif logical_name == "consistency_score":

            included = False
            exclusion_reason = (
                "DIAGNOSTIC_ONLY"
                if not constant
                else "CONSTANT_DIAGNOSTIC_COMPONENT"
            )

        elif constant:

            exclusion_reason = (
                "CONSTANT_COMPONENT"
            )

        elif logical_name not in INCREMENTAL_WEIGHTS:

            exclusion_reason = (
                "NOT_AN_INCREMENTAL_COMPONENT"
            )

        else:

            exclusion_reason = None

        records.append({
            "component": logical_name,
            "source_column": column,
            "present": True,
            "row_count": len(ranking_df),
            "non_null_rows": int(
                valid.shape[0]
            ),
            "unique_values": unique_count,
            "mean": (
                float(valid.mean())
                if len(valid)
                else np.nan
            ),
            "std": std,
            "min": (
                float(valid.min())
                if len(valid)
                else np.nan
            ),
            "max": (
                float(valid.max())
                if len(valid)
                else np.nan
            ),
            "constant": constant,
            "usable_for_calibration": (
                len(valid) > 0
                and not constant
            ),
            "included_in_calibration": included,
            "exclusion_reason": exclusion_reason,
        })

    return pd.DataFrame(
        records
    )


