# ============================================================================

def _robust_center_scale(
    reference: pd.Series,
) -> Tuple[float, float, str]:

    values = pd.to_numeric(
        reference,
        errors="coerce",
    )

    values = values[
        np.isfinite(values)
    ]

    if len(values) == 0:
        return np.nan, np.nan, "NO_VALID_REFERENCE"

    median = float(
        values.median()
    )

    q1 = float(
        values.quantile(0.25)
    )

    q3 = float(
        values.quantile(0.75)
    )

    iqr = q3 - q1

    if np.isfinite(iqr) and iqr > ROBUST_SCALE_EPSILON:
        return median, iqr, "IQR"

    mad = float(
        np.median(
            np.abs(
                values - median
            )
        )
    )

    if np.isfinite(mad) and mad > ROBUST_SCALE_EPSILON:
        return median, mad * 1.4826, "MAD"

    std = float(
        values.std(
            ddof=0
        )
    )

    if np.isfinite(std) and std > ROBUST_SCALE_EPSILON:
        return median, std, "STD"

    # Constant peer population.
    return median, np.nan, "CONSTANT"


def peer_relative_component(
    series: pd.Series,
    reference_mask: Optional[pd.Series] = None,
) -> pd.Series:

    values = normalize_component(
        series
    )

    if reference_mask is None:

        reference = values

    else:

        reference_mask = pd.Series(
            reference_mask,
            index=values.index,
        ).fillna(False).astype(bool)

        reference = values[
            reference_mask
        ]

    center, scale, method = _robust_center_scale(
        reference
    )

    if (
        not np.isfinite(center)
        or not np.isfinite(scale)
    ):

        return values.where(
            values.isna(),
            0.0,
        )

    result = (
        (values - center)
        / scale
    ).clip(
        -ROBUST_CLIP,
        ROBUST_CLIP,
    )

    return result


