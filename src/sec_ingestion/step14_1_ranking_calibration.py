# ============================================================================
# BUILD COMPANY SNAPSHOT
# ============================================================================

def build_company_snapshot(
    ranking_df: pd.DataFrame,
) -> pd.DataFrame:

    if ranking_df.empty:
        return ranking_df.copy()

    sort_columns = [
        column
        for column in [
            "fiscal_year",
            "quarter",
        ]
        if column in ranking_df.columns
    ]

    if sort_columns:

        ranking_df = ranking_df.sort_values(
            sort_columns,
            kind="mergesort",
        )

    # Step 14 is expected to provide the latest company ranking.
    return ranking_df.tail(
        1
    ).copy()


