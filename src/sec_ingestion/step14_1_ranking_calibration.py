def read_parquet(path: Path, label: str) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(
            f"{label} not found: {path}"
        )

    df = pd.read_parquet(path)

    if not isinstance(df, pd.DataFrame):
        raise TypeError(
            f"{label} did not load as DataFrame: {path}"
        )

    return df


def write_parquet(
    df: pd.DataFrame,
    path: Path,
) -> None:

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    df.to_parquet(
        path,
        index=False,
    )


def numeric_series(
    df: pd.DataFrame,
    column: str,
) -> pd.Series:

    if column not in df.columns:
        return pd.Series(
            np.nan,
            index=df.index,
            dtype="float64",
        )

    return pd.to_numeric(
        df[column],
        errors="coerce",
    )


def normalize_component(
    series: pd.Series,
) -> pd.Series:

    values = pd.to_numeric(
        series,
        errors="coerce",
    )

    values = values.where(
        np.isfinite(values),
        np.nan,
    )

    # Component contract is 0-100.
    return values.clip(
        lower=0,
        upper=100,
    )


def resolve_component(
    df: pd.DataFrame,
    aliases: List[str],
) -> Optional[str]:

    for column in aliases:
        if column in df.columns:
            return column

    return None


def resolve_components(
    df: pd.DataFrame,
) -> Dict[str, Optional[str]]:

    return {
        logical_name: resolve_component(
            df,
            aliases,
        )
        for logical_name, aliases
        in OPTIONAL_COMPONENT_ALIASES.items()
    }


