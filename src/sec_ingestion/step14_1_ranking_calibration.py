def correlation_report(
    ranking_df: pd.DataFrame,
    components: Dict[str, Optional[str]],
) -> pd.DataFrame:

    records = []

    base = numeric_series(
        ranking_df,
        "financial_score",
    )

    for logical_name, column in components.items():

        if column is None:
            continue

        component = numeric_series(
            ranking_df,
            column,
        )

        values = pd.DataFrame({
            "base": base,
            "component": component,
        }).dropna()

        if len(values) < 3:

            correlation = np.nan

        else:

            base_std = values[
                "base"
            ].std(ddof=0)

            component_std = values[
                "component"
            ].std(ddof=0)

            if (
                base_std <= VARIANCE_EPSILON
                or component_std <= VARIANCE_EPSILON
            ):
                correlation = np.nan
            else:
                correlation = float(
                    values[
                        "base"
                    ].corr(
                        values[
                            "component"
                        ]
                    )
                )

        if (
            logical_name
            == "financial_strength_score"
        ):

            severity = (
                "HIGH"
                if (
                    np.isfinite(correlation)
                    and abs(correlation)
                    >= HIGH_CORRELATION_THRESHOLD
                )
                else "INFO"
            )

            comparison = (
                "base_score_vs_financial_strength"
            )

        else:

            severity = (
                "HIGH"
                if (
                    np.isfinite(correlation)
                    and abs(correlation)
                    >= HIGH_CORRELATION_THRESHOLD
                )
                else "INFO"
            )

            comparison = (
                "base_score_vs_component"
            )

        records.append({
            "component": logical_name,
            "comparison": comparison,
            "correlation": correlation,
            "absolute_correlation": (
                abs(correlation)
                if np.isfinite(correlation)
                else np.nan
            ),
            "severity": severity,
        })

    return pd.DataFrame(
        records
    )


