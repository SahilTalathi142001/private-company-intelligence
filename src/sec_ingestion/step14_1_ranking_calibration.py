def load_validation_gate(
    validation_path: Path,
) -> Tuple[
    pd.DataFrame,
    pd.DataFrame,
]:

    company_path = (
        validation_path
        / "company_feature_summary"
        / "company_feature_summary.parquet"
    )

    summary_path = (
        validation_path
        / "feature_validation_summary"
        / "feature_validation_summary.parquet"
    )

    company_df = read_parquet(
        company_path,
        "Step 12.1 company audit summary",
    )

    summary_df = read_parquet(
        summary_path,
        "Step 12.1 validation summary",
    )

    if "audit_status" not in company_df.columns:

        raise ValueError(
            "Step 12.1 company summary does not contain audit_status."
        )

    statuses = (
        company_df[
            "audit_status"
        ]
        .astype("string")
        .str.upper()
        .str.strip()
    )

    if not (
        statuses == "PASS"
    ).all():

        failing = company_df.loc[
            statuses != "PASS",
            [
                "cik",
                "audit_status",
            ],
        ]

        raise RuntimeError(
            "Step 12.1 feature-quality gate failed:\n"
            f"{failing.to_string(index=False)}"
        )

    return company_df, summary_df


