def partition_scored_companies(
    snapshot: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Split a peer universe into calibratable and legitimately unscored companies.

    Step 13 leaves financial_score empty when the company is
    INSUFFICIENT_DATA. That is a valid upstream state. A missing score must
    not abort calibration for every other company. A finite score outside
    0-100 remains a hard failure.
    """
    scores = numeric_series(snapshot, "financial_score")
    finite = np.isfinite(scores.to_numpy(dtype=float))
    out_of_range = finite & (
        (scores.to_numpy(dtype=float) < 0)
        | (scores.to_numpy(dtype=float) > 100)
    )

    if out_of_range.any():
        bad = snapshot.loc[out_of_range, ["cik"]].copy()
        bad["financial_score"] = scores.loc[out_of_range].to_numpy()
        raise ValueError(
            "Step 13 financial_score contains invalid values: "
            f"{bad.to_dict('records')}"
        )

    status = (
        snapshot["financial_score_status"].astype(str).str.upper()
        if "financial_score_status" in snapshot.columns
        else pd.Series("", index=snapshot.index)
    )
    health = (
        snapshot["financial_health"].astype(str).str.upper()
        if "financial_health" in snapshot.columns
        else pd.Series("", index=snapshot.index)
    )
    insufficient = (~finite) & (
        status.eq("INSUFFICIENT_DATA") | health.eq("INSUFFICIENT_DATA")
    )
    unexplained = (~finite) & ~insufficient

    if unexplained.any():
        bad = snapshot.loc[unexplained, ["cik"]].copy()
        bad["financial_score"] = scores.loc[unexplained].to_numpy()
        raise ValueError(
            "Step 13 financial_score contains invalid values: "
            f"{bad.to_dict('records')}"
        )

    eligible = snapshot.loc[finite].copy()
    excluded = snapshot.loc[insufficient].copy()

    if eligible.empty:
        raise RuntimeError(
            "No companies with a finite Step 13 financial_score "
            "are available for calibration."
        )

    # region agent log
    _debug_log(
        "A",
        "step14_1_ranking_calibration.py:partition_scored_companies",
        "calibration universe partition",
        {
            "eligible": int(len(eligible)),
            "unscored": int(len(excluded)),
            "unscored_ciks": excluded["cik"].astype(str).tolist(),
        },
    )
    # endregion

    return eligible, excluded


def append_unscored_companies(
    calibrated: pd.DataFrame,
    excluded: pd.DataFrame,
) -> pd.DataFrame:
    """Keep unscored companies in the calibration universe without a fabricated score."""
    if excluded.empty:
        return calibrated

    peer_sample_size = int(calibrated["peer_sample_size"].iloc[0])
    peer_sample_class = (
        str(calibrated["peer_sample_class"].iloc[0])
        if "peer_sample_class" in calibrated.columns
        else "SMALL"
    )
    rows = []

    for _, source in excluded.iterrows():
        row = {
            column: source[column] if column in source.index else pd.NA
            for column in calibrated.columns
        }
        row.update({
            "base_financial_score": np.nan,
            "raw_calibration_adjustment": np.nan,
            "bounded_calibration_adjustment": np.nan,
            "calibration_adjustment": np.nan,
            "calibration_cap_applied": False,
            "calibration_cap_direction": "NONE",
            "calibrated_ranking_score": np.nan,
            "calibrated_display_score": np.nan,
            "calibration_adjustment_pct": np.nan,
            "calibration_direction": "UNSCORED",
            "calibration_magnitude": "NONE",
            "raw_adjustment_magnitude": "NONE",
            "calibration_confidence": "LOW",
            "calibration_confidence_reason": (
                "Step 13 financial_score is unavailable because the company "
                "is INSUFFICIENT_DATA. Excluded from peer calibration."
            ),
            "calibrated_financial_health": "INSUFFICIENT_DATA",
            "calibrated_overall_rank": np.nan,
            "calibrated_ranking_percentile": np.nan,
            "peer_sample_size": peer_sample_size,
            "peer_sample_class": peer_sample_class,
        })
        rows.append(row)

    extra = pd.DataFrame(rows, columns=calibrated.columns)
    populated = [
        column for column in extra.columns
        if extra[column].notna().any()
    ]
    return pd.concat(
        [calibrated, extra[populated]],
        ignore_index=True,
    )


def calculate_calibration(
    df: pd.DataFrame,
    components: Dict[str, Optional[str]],
) -> pd.DataFrame:

    result = df.copy()

    result[
        "base_financial_score"
    ] = numeric_series(
        result,
        "financial_score",
    )

    invalid_base = (
        ~np.isfinite(
            result[
                "base_financial_score"
            ]
        )
        |
        (
            result[
                "base_financial_score"
            ] < 0
        )
        |
        (
            result[
                "base_financial_score"
            ] > 100
        )
    )

    if invalid_base.any():

        raise ValueError(
            "Step 13 financial_score contains invalid values."
        )

    peer_sample_size = len(result)

    result[
        "peer_sample_size"
    ] = peer_sample_size

    if peer_sample_size >= MIN_PEERS_FOR_HIGH_CONFIDENCE:

        peer_sample_class = "SUFFICIENT"

    elif peer_sample_size >= MIN_PEERS_FOR_MEDIUM_CONFIDENCE:

        peer_sample_class = "LIMITED"

    else:

        peer_sample_class = "SMALL"

    result[
        "peer_sample_class"
    ] = peer_sample_class

    adjustment_terms = []

    # ------------------------------------------------------------------
    # Independent incremental components
    # ------------------------------------------------------------------

    for logical_name in (
        "growth_score",
        "profitability_score",
        "momentum_score",
        "risk_score",
    ):

        column = components.get(
            logical_name
        )

        if column is None:

            raise ValueError(
                "Required calibration component missing: "
                f"{logical_name}"
            )

        score = normalize_component(
            result[column]
        )

        result[
            f"{logical_name}_calibration_score"
        ] = score

        centered = peer_relative_component(
            score
        )

        centered = centered.fillna(
            0.0
        )

        if (
            logical_name == "risk_score"
            and not RISK_SCORE_HIGH_IS_GOOD
        ):

            centered = -centered

        weight_key = logical_name.replace(
            "_score",
            "",
        )

        weighted = (
            centered
            * INCREMENTAL_WEIGHTS[
                weight_key
            ]
        )

        result[
            f"{logical_name}_calibration_signal"
        ] = centered

        result[
            f"{logical_name}_calibration_contribution"
        ] = (
            weighted
            * MAX_ADJUSTMENT_POINTS
        )

        adjustment_terms.append(
            weighted
        )

    # ------------------------------------------------------------------
    # Raw adjustment
    # ------------------------------------------------------------------

    raw_adjustment_ratio = sum(
        adjustment_terms
    )

    raw_adjustment_points = (
        raw_adjustment_ratio
        * MAX_ADJUSTMENT_POINTS
    )

    result[
        "raw_calibration_adjustment"
    ] = raw_adjustment_points

    # ------------------------------------------------------------------
    # Production bounded adjustment
    # ------------------------------------------------------------------

    bounded_adjustment = raw_adjustment_points.clip(
        lower=-MAX_ADJUSTMENT_POINTS,
        upper=MAX_ADJUSTMENT_POINTS,
    )

    result[
        "bounded_calibration_adjustment"
    ] = bounded_adjustment

    # Preserve the original field name.
    result[
        "calibration_adjustment"
    ] = bounded_adjustment

    result[
        "calibration_cap_applied"
    ] = (
        np.abs(
            raw_adjustment_points
        )
        >
        MAX_ADJUSTMENT_POINTS
        + 1e-9
    )

    result[
        "calibration_cap_direction"
    ] = np.select(
        [
            raw_adjustment_points
            > MAX_ADJUSTMENT_POINTS,

            raw_adjustment_points
            < -MAX_ADJUSTMENT_POINTS,
        ],
        [
            "POSITIVE_CAP",
            "NEGATIVE_CAP",
        ],
        default="NONE",
    )

    # ------------------------------------------------------------------
    # Final score
    # ------------------------------------------------------------------

    result[
        "calibrated_ranking_score"
    ] = (
        result[
            "base_financial_score"
        ]
        +
        result[
            "calibration_adjustment"
        ]
    )

    result[
        "calibrated_display_score"
    ] = result[
        "calibrated_ranking_score"
    ].clip(
        lower=0,
        upper=100,
    )

    result[
        "calibration_adjustment_pct"
    ] = np.where(
        result[
            "base_financial_score"
        ] != 0,

        result[
            "calibration_adjustment"
        ]
        /
        result[
            "base_financial_score"
        ],

        np.nan,
    )

    # ------------------------------------------------------------------
    # Direction
    # ------------------------------------------------------------------

    result[
        "calibration_direction"
    ] = np.select(
        [
            result[
                "calibration_adjustment"
            ] > 0.25,

            result[
                "calibration_adjustment"
            ] < -0.25,
        ],
        [
            "POSITIVE",
            "NEGATIVE",
        ],
        default="NEUTRAL",
    )

    # ------------------------------------------------------------------
    # Magnitude
    # ------------------------------------------------------------------

    result[
        "calibration_magnitude"
    ] = np.select(
        [
            result[
                "calibration_adjustment"
            ].abs()
            >= LARGE_ADJUSTMENT_THRESHOLD,

            result[
                "calibration_adjustment"
            ].abs()
            >= 3.0,
        ],
        [
            "LARGE",
            "MODERATE",
        ],
        default="SMALL",
    )

    result[
        "raw_adjustment_magnitude"
    ] = np.select(
        [
            result[
                "raw_calibration_adjustment"
            ].abs()
            >= RAW_LARGE_ADJUSTMENT_THRESHOLD,

            result[
                "raw_calibration_adjustment"
            ].abs()
            >= 5.0,
        ],
        [
            "LARGE",
            "MODERATE",
        ],
        default="SMALL",
    )

    # ------------------------------------------------------------------
    # Confidence
    # ------------------------------------------------------------------

    inherited_confidence = (
        result[
            "financial_signal_confidence"
        ]
        .astype("string")
        .str.upper()
        .str.strip()
    )

    inherited_rank = inherited_confidence.map({
        "HIGH": 3,
        "MEDIUM": 2,
        "LOW": 1,
    }).fillna(1)

    if peer_sample_size >= MIN_PEERS_FOR_HIGH_CONFIDENCE:

        result[
            "calibration_confidence"
        ] = inherited_confidence.map({
            "HIGH": "HIGH",
            "MEDIUM": "MEDIUM",
            "LOW": "LOW",
        }).fillna("LOW")

    elif peer_sample_size >= MIN_PEERS_FOR_MEDIUM_CONFIDENCE:

        result[
            "calibration_confidence"
        ] = inherited_confidence.map({
            "HIGH": "MEDIUM",
            "MEDIUM": "MEDIUM",
            "LOW": "LOW",
        }).fillna("LOW")

    else:

        result[
            "calibration_confidence"
        ] = inherited_confidence.map({
            "HIGH": "MEDIUM",
            "MEDIUM": "MEDIUM",
            "LOW": "LOW",
        }).fillna("LOW")

    result[
        "calibration_confidence_reason"
    ] = np.where(
        peer_sample_size
        <
        MIN_PEERS_FOR_HIGH_CONFIDENCE,

        "Peer population below minimum "
        "for high-confidence calibration.",

        "Peer population sufficient "
        "for inherited confidence.",
    )

    # ------------------------------------------------------------------
    # Final health
    # ------------------------------------------------------------------

    score = result[
        "calibrated_display_score"
    ]

    result[
        "calibrated_financial_health"
    ] = np.select(
        [
            score >= 90,
            score >= 75,
            score >= 60,
        ],
        [
            "EXCELLENT",
            "STRONG",
            "HEALTHY",
        ],
        default="MIXED",
    )

    # ------------------------------------------------------------------
    # Ranking
    # ------------------------------------------------------------------

    result = result.sort_values(
        "calibrated_ranking_score",
        ascending=False,
        kind="mergesort",
    ).reset_index(
        drop=True
    )

    result[
        "calibrated_overall_rank"
    ] = (
        np.arange(
            len(result)
        )
        + 1
    )

    n = len(result)

    if n > 1:

        result[
            "calibrated_ranking_percentile"
        ] = (
            (
                n
                -
                result[
                    "calibrated_overall_rank"
                ]
            )
            /
            (n - 1)
            * 100
        )

    else:

        result[
            "calibrated_ranking_percentile"
        ] = 100.0

    return result


